import type { INodeProperties } from 'n8n-workflow';

const luauExecutionBaseUrl = '=/cloud/v2/universes/{{ $parameter["universeId"] }}';
const luauExecutionPlaceUrl = `${luauExecutionBaseUrl}/places/{{ $parameter["placeId"] }}`;
const luauExecutionVersionUrl =
	`${luauExecutionPlaceUrl}/versions/{{ $parameter["versionId"] }}`;
const luauExecutionSessionTaskUrl =
	`${luauExecutionVersionUrl}/luau-execution-sessions/` +
	'{{ $parameter["luauExecutionSessionId"] }}/tasks/{{ $parameter["taskId"] }}';

const taskCreationOperations = ['create_session_task', 'create_session_task_for_version'];
const taskReadOperations = ['get_session_task', 'list_session_task_logs'];
const operationsWithUniverse = [
	'create_session_task_binary_input',
	...taskCreationOperations,
	...taskReadOperations,
];
const operationsWithPlace = [...taskCreationOperations, ...taskReadOperations];
const operationsWithVersion = ['create_session_task_for_version', ...taskReadOperations];

const sessionTaskBody = `={{ Object.assign(
	{
		script: $parameter["script"],
		enableBinaryOutput: $parameter["enableBinaryOutput"],
	},
	$parameter["timeout"] ? { timeout: $parameter["timeout"] } : {},
	$parameter["binaryInput"] ? { binaryInput: $parameter["binaryInput"] } : {}
) }}`;

